let currentLanguage = 'en';

function t(key, params = {}) {
    const langDict = translations[currentLanguage] || translations['en'];
    let text = langDict[key] || (translations['en'] && translations['en'][key]) || key;
    
    // Replace parameter placeholders e.g. {selected}, {total}, {threads}, {pkg}, {ver}
    for (const [paramKey, paramVal] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), paramVal);
    }
    return text;
}

function getCurrentLanguage() {
    return currentLanguage;
}

function applyLanguage(lang) {
    if (!translations[lang]) {
        lang = 'en';
    }
    currentLanguage = lang;
    document.documentElement.lang = lang;
    
    // Update all static elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translated = t(key);
        if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit')) {
            el.value = translated;
        } else {
            el.innerHTML = translated;
        }
    });

    // Update placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = t(key);
    });

    // Update titles/tooltips with data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        el.title = t(key);
    });

    // Re-create icons in case any were affected
    if (window.lucide) {
        window.lucide.createIcons();
    }
}
